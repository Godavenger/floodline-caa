    pilot = json.loads(settings.fixture.read_text(encoding="utf-8"))
    with (ROOT / "data/fixtures/synthetic_evaluation.csv").open(encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle))
    ledger = {}
    for row in rows:
        if row["label"] not in ("0", "1"):
            continue
        ledger[(row["event_id"], row["area_id"])] = {"event_id": row["event_id"], "area_id": row["area_id"],
            "onset": row["onset"], "label_state": "synthetic_positive" if row["label"] == "1" else "synthetic_negative",
            "evidence_reference": row["evidence_reference"], "negative_supported": row["negative_supported"], "field_reviewed": False}
    with (folder / "synthetic-event-ledger.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(next(iter(ledger.values()))))
        writer.writeheader(); writer.writerows(ledger.values())
    error_rows = []
    for model, metrics in [("candidate", result["candidate"]["test"]), ("rainfall_baseline", result["rainfall_baseline"])]:
        for kind in ["event", "area"]:
            error_rows.extend({"method": model, "group": kind, "id": key, **value} for key, value in metrics["by_" + kind].items())
    with (folder / "errors.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(error_rows[0]))
        writer.writeheader(); writer.writerows(error_rows)
    collection = {"type": "FeatureCollection", "mode": "synthetic", "dataset_sha256": result["dataset_sha256"], "features": [
        {"type": "Feature", "geometry": area["geometry"], "properties": {"area_id": area["id"], **result["candidate"]["test"]["by_area"][area["id"]],
         "meaning": "Synthetic held-out classification errors; not real flood risk"}} for area in pilot["areas"]]}
