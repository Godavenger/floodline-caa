def write_json(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def export_figures(result, pilot, folder):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.colors import LinearSegmentedColormap
    from matplotlib.patches import Polygon
    import numpy as np

    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 10, "axes.spines.top": False,
                         "axes.spines.right": False, "axes.labelcolor": "#21343d", "text.color": "#21343d"})
    cmap = LinearSegmentedColormap.from_list("floodline", ["#edf3f5", "#087f82"])
    fig, axes = plt.subplots(1, 2, figsize=(9.2, 4.2))
    for ax, title, data in zip(axes, ["Candidate · threshold 0.3", "Rainfall-only baseline · 75 mm"],
                               [result["candidate"]["test"], result["rainfall_baseline"]]):
        counts = data["confusion_matrix"]
        values = np.array([[counts["tn"], counts["fp"]], [counts["fn"], counts["tp"]]])
        ax.imshow(values, cmap=cmap, vmin=0, vmax=max(1, data["positive_labels"]))
        for y in range(2):
            for x in range(2):
                ax.text(x, y, str(values[y, x]), ha="center", va="center", fontsize=22,
                        color="white" if values[y, x] > data["positive_labels"] / 2 else "#21343d")
        ax.set_xticks([0, 1], ["No warning", "Warning"])
        ax.set_yticks([0, 1], ["Negative label", "Positive label"])
        ax.set_xlabel("Predicted decision")
        ax.set_title(title, fontsize=12, pad=14)
    fig.suptitle("Synthetic held-out decisions — 4 events, 138 rows", fontsize=15, x=.04, ha="left")
    fig.text(.04, .015, "Software experiment only. Synthetic labels do not establish historical flood-prediction accuracy.", fontsize=9)
    fig.tight_layout(rect=(0, .07, 1, .9))
    provenance = {"Title": "Synthetic Floodline evaluation", "Description": "Generated by scripts/export_evidence.py; dataset SHA-256 " + result["dataset_sha256"],
                  "Software": "Matplotlib " + matplotlib.__version__}
    fig.savefig(folder / "confusion.png", dpi=180, metadata=provenance)
    fig.savefig(folder / "confusion.pdf")
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(6.2, 5.4))
    errors = result["candidate"]["test"]["by_area"]
    for area in pilot["areas"]:
        points = area["geometry"]["coordinates"][0]
        values = errors[area["id"]]
        count = values["missed"] + values["false_alarms"]
        ax.add_patch(Polygon(points, facecolor=cmap(count / max(1, values["rows"])), edgecolor="white", linewidth=2))
        x = sum(point[0] for point in points[:-1]) / (len(points) - 1)
        y = sum(point[1] for point in points[:-1]) / (len(points) - 1)
        ax.text(x, y, area["id"] + "\n" + str(count) + " / " + str(values["rows"]) + " rows", ha="center", va="center", fontsize=10)
    ax.autoscale()
    ax.set_aspect(1 / math.cos(math.radians(22.57)))
    ax.set_xlabel("Longitude · synthetic WGS84 geometry")
    ax.set_ylabel("Latitude")
    ax.set_title("Candidate errors by synthetic cell\nFalse-positive + missed rows", loc="left", fontsize=14, pad=16)
    ax.ticklabel_format(useOffset=False)
    fig.text(.12, .015, "A diagnostic of generated labels, not a map of real flood risk.", fontsize=9)
    fig.tight_layout(rect=(0, .06, 1, 1))
    fig.savefig(folder / "error-map.png", dpi=180, metadata=provenance)
    fig.savefig(folder / "error-map.pdf")
    plt.close(fig)


def measure_local(url, folder):
    write_json(folder / "openapi.json", json.load(urlopen(url.rstrip("/") + "/openapi.json", timeout=10)))
    def request(_):
        started = time.perf_counter()
        with urlopen(url.rstrip("/") + "/api/dashboard", timeout=10) as response:
            payload = json.load(response)
            assert payload["mode"] == "synthetic" and payload["summary"]["cells"] == 9
        return round((time.perf_counter() - started) * 1000, 2)
    with ThreadPoolExecutor(max_workers=10) as pool:
        samples = list(pool.map(request, range(20)))
    ordered = sorted(samples)
    result = {"at": datetime.now(timezone.utc).isoformat(), "endpoint": "/api/dashboard",
              "clients": 10, "requests": 20, "mode": "synthetic", "storage": "sqlite-local",
              "median_ms": statistics.median(samples), "p95_ms": ordered[math.ceil(.95 * len(samples)) - 1],
              "max_ms": max(samples), "samples_ms": samples, "target_p95_ms": 3000,
              "target_met": ordered[math.ceil(.95 * len(samples)) - 1] < 3000,
              "scope": "Loopback requests on the recorded local setup; excludes upstream feed/provider latency and city-scale load."}
    write_json(folder / "performance.json", result)
    return result


def copy_notices():
    libraries = ["react", "react-dom", "scheduler", "leaflet", "react-leaflet", "@react-leaflet/core",
                 "lucide-react", "@fontsource-variable/manrope"]
    rows = []
    for name in libraries:
        source = ROOT / "frontend/node_modules" / name
        metadata = json.loads((source / "package.json").read_text(encoding="utf-8"))
        destination = ROOT / "third_party" / name.replace("@", "").replace("/", "-")
        destination.mkdir(parents=True, exist_ok=True)
        notices = [path for path in source.iterdir() if path.is_file() and path.name.upper().startswith(("LICENSE", "LICENCE", "OFL", "NOTICE"))]
        for path in notices:
            shutil.copy2(path, destination / path.name)
        rows.append("| " + name + " | " + metadata["version"] + " | " + metadata.get("license", "See package notice") + " | " + str(destination.relative_to(ROOT)).replace("\\", "/") + " |")
    text = "# Third-party notices\n\nThe built interface redistributes the following libraries and locally bundled font. Their original licence notices are included under third_party/.\n\n"
    text += "| Package | Version | Declared licence | Notice folder |\n| --- | --- | --- | --- |\n" + "\n".join(rows)
    text += "\n\nPython dependencies are installed from their pinned package distributions, rather than vendored in this source release. Their respective licences remain in those distributions. Optional OpenStreetMap tiles retain attribution in the map. All pilot roads, wards, environmental observations and evaluation labels are project-authored synthetic fixtures.\n"
    (ROOT / "THIRD_PARTY.md").write_text(text, encoding="utf-8")


def render_report(markdown, folder):
    import re
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image, PageBreak
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(name="BodyProject", fontName="Helvetica", fontSize=10.5, leading=15, spaceAfter=9, textColor=colors.HexColor("#21343d")))
    styles.add(ParagraphStyle(name="CellProject", fontName="Helvetica", fontSize=8.5, leading=12, textColor=colors.HexColor("#21343d")))
    doc = SimpleDocTemplate(str(ROOT / "outputs/Floodline_Project_Report.pdf"), pagesize=A4, rightMargin=42, leftMargin=42, topMargin=45, bottomMargin=45)
    story, table_rows = [], []
    def plain(text):
        return escape(re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text).replace("**", ""))
    def flush_table():
        if not table_rows:
            return
        cells = [[Paragraph(plain(cell), styles["CellProject"]) for cell in row] for row in table_rows]
        table = Table(cells, colWidths=[doc.width / len(cells[0])] * len(cells[0]), repeatRows=1, hAlign="LEFT")
        table.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#edf3f5")),
                                   ("VALIGN", (0, 0), (-1, -1), "TOP"), ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
                                   ("TOPPADDING", (0, 0), (-1, -1), 8), ("LINEBELOW", (0, 0), (-1, -1), .3, colors.HexColor("#d9e3e5"))]))
        story.extend([table, Spacer(1, 12)])
        table_rows.clear()
    for line in markdown.splitlines():
        if line.startswith("|"):
            row = [cell.strip() for cell in line.strip("|").split("|")]
            if not all(set(cell) <= set("- :") for cell in row):
                table_rows.append(row)
            continue
        flush_table()
        if not line.strip():
            continue
        if line.startswith("!["):
            name = "confusion.png" if "confusion.png" in line else "error-map.png"
            image = Image(str(folder / name))
            image.drawHeight *= doc.width / image.drawWidth
            image.drawWidth = doc.width
            story.extend([image, Spacer(1, 12)])
        elif line.startswith("# "):
            story.append(Paragraph(plain(line[2:]), styles["Title"]))
        elif line.startswith("## "):
            if line == "## Reference starting points":
                story.append(PageBreak())
            story.append(Paragraph(plain(line[3:]), styles["Heading2"]))
        else:
            story.append(Paragraph(plain(line), styles["BodyProject"]))
    flush_table()
    def page(canvas, _):
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(colors.HexColor("#586a73"))
        canvas.drawString(42, 24, f"Floodline | Synthetic CAA prototype | v{__version__}")
        canvas.drawRightString(A4[0] - 42, 24, str(canvas.getPageNumber()))
    doc.build(story, onFirstPage=page, onLaterPages=page)


